interface DbRoleRow {
  id: string;
  key: string;
  name: string;
  description: string | null;
  is_system: boolean;
}

interface DbPermissionRow {
  key: string;
  module_key: string;
  kind: "view" | "write";
  label: string;
  description: string | null;
  sort: number;
}

interface DbRolePermRow {
  role_id: string;
  permission_key: string;
}

export async function getSystemRoles(): Promise<{
  roles: SystemRole[];
  permissions: SystemPermission[];
}> {
  try {
    const supabase = await createClient();
    const [
      { data: rolesData },
      { data: permissionsData },
      { data: rolePermsData },
    ] = await Promise.all([
      supabase.from("roles").select("id, key, name, description, is_system"),
      supabase
        .from("permissions")
        .select("key, module_key, kind, label, description, sort"),
      supabase.from("role_permissions").select("role_id, permission_key"),
    ]);

    if (rolesData && rolesData.length > 0) {
      const typedRoles = rolesData as unknown as DbRoleRow[];
      const typedRolePerms = (rolePermsData ||
        []) as unknown as DbRolePermRow[];
      const typedPerms = (permissionsData ||
        []) as unknown as DbPermissionRow[];

      const permsMap = typedRolePerms.reduce(
        (acc: Record<string, string[]>, curr) => {
          acc[curr.role_id] = acc[curr.role_id] || [];
          acc[curr.role_id].push(curr.permission_key);
          return acc;
        },
        {},
      );

      const ROLE_ORDER: Record<string, number> = {
        receptionist: 1,
        branch_manager: 2,
        sales: 3,
        technician: 4,
        owner: 5,
      };

      const formattedRoles: SystemRole[] = typedRoles
        .map((r) => ({
          id: r.id,
          key: r.key,
          name: r.name,
          description: r.description,
          isSystem: r.is_system,
          permissionKeys: permsMap[r.id] || [],
        }))
        .sort((a, b) => (ROLE_ORDER[a.key] || 99) - (ROLE_ORDER[b.key] || 99));

      // Merge DB permissions metadata with rich SYSTEM_PERMISSIONS_CATALOG
      const dbPermsMap = new Map(typedPerms.map((p) => [p.key, p]));
      const fullPermissions = SYSTEM_PERMISSIONS_CATALOG.map((p) => {
        const dbPerm = dbPermsMap.get(p.key);
        if (dbPerm) {
          return {
            ...p,
            label: dbPerm.label || p.label,
            description: dbPerm.description || p.description,
          };
        }
        return p;
      });

      return {
        roles: formattedRoles,
        permissions: fullPermissions,
      };
    }
  } catch {
    // Fallback when Supabase container is initializing
  }

  return {
    roles: DEFAULT_SYSTEM_ROLES,
    permissions: SYSTEM_PERMISSIONS_CATALOG,
  };
}
